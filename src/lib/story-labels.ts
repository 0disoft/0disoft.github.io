export function getStoryLabel(
	id: string,
	locale: SiteLocale,
	t: SiteTranslate = getSiteTranslator(locale).t,
): string {
	const key = `site:stories_${id.replaceAll("-", "_")}` as SiteMessageKey;
	if (!storyMessageKeys.has(key)) throw new Error(`Missing story filter label: ${key}`);
	return t(...([key] as TypedCall<AppSchema>));
}
